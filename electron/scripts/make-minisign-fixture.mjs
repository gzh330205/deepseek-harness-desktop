#!/usr/bin/env node
/**
 * Pack the signed fixture into JSON so the app can verify a real signature in its own
 * runtime.
 *
 * The smoke run in `src/main.ts` has to prove that verification works under Electron, whose
 * BoringSSL has no BLAKE2b. Reading the fixture from disk would work in development and fail
 * from inside `app.asar`, and it is exactly that runtime difference that let a broken
 * verifier ship, so the bytes are embedded into the bundle instead.
 *
 * Usage: node scripts/make-minisign-fixture.mjs
 */

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const artifact = readFileSync(join(root, 'src', 'fixtures', 'artifact.txt'))
const signature = readFileSync(join(root, 'src', 'fixtures', 'artifact.txt.sig'), 'utf8').trim()

const packed = {
  note: 'Generated by scripts/make-minisign-fixture.mjs. Signed with the repository key; the public key ships in src-tauri/tauri.conf.json.',
  artifactSha256: createHash('sha256').update(artifact).digest('hex'),
  artifactBase64: artifact.toString('base64'),
  signature,
}
writeFileSync(join(root, 'src', 'fixtures', 'minisign-smoke.json'), `${JSON.stringify(packed, null, 2)}\n`, 'utf8')
process.stdout.write(`fixture: ${String(artifact.length)} bytes, sha256 ${packed.artifactSha256.slice(0, 16)}…\n`)
